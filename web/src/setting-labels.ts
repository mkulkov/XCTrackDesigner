export function settingChoices(
  key: string,
  nativeDefault: unknown,
  widgetClass = '',
): string[] | undefined {
  if (key === 'rotation' && typeof nativeDefault === 'string')
    return ['NORTH', 'HEADING', 'BEARING', 'TRAVEL_DIRECTION']
  if (key === 'type' && nativeDefault === 'GRAPH_THERMAL')
    return ['GRAPH_THERMAL', 'GRAPH_WIND', 'GRAPH_SPEED']
  if (key === 'type' && nativeDefault === 'SIDE_BEARING') return ['SIDE_BEARING', 'SIDE_NAVIG']
  if (key === 'relative' && nativeDefault === 'ABSOLUTE_TIME')
    return ['ABSOLUTE_TIME', 'RELATIVE_TIME']
  if (key === 'type' && nativeDefault === 'ACTION_ZOOM_IN')
    return ['ACTION_ZOOM_IN', 'ACTION_ZOOM_OUT']
  if (key === 'type' && nativeDefault === 'ACTION_NEXT_WAYPOINT')
    return ['ACTION_NEXT_WAYPOINT', 'ACTION_PREV_WAYPOINT']
  if (key === '_units' && nativeDefault === 'SYS_UNIT')
    return widgetClass.endsWith('.WSpeed')
      ? ['SYS_UNIT', 'KM_H', 'M_S', 'MP_H', 'KT']
      : ['SYS_UNIT', 'METER', 'FOOT', 'YARD']
  if (key === '_units' && nativeDefault === 'CELSIUS') return ['CELSIUS', 'FAHRENHEIT']
  if (key === 'speed_type' && nativeDefault === 'TAS') return ['TAS', 'IAS']
  if (key === 'fontSize' && nativeDefault === 'SMALL') return ['SMALL', 'MEDIUM', 'LARGE']
  return enumGroups[key]
}

